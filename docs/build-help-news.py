"""Write the newest CHANGELOG.md entries into the help's What's new.

    python docs/build-help-news.py

The app is one file that loads nothing, and a page opened from disk cannot
read CHANGELOG.md beside it, so the newest entries are copied into the
HELP_NEWS line of grouptodo.html, between its two markers. tests/run.mjs runs
this before every battery, so a pushed version always carries its own news.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "grouptodo.html")
LOG = os.path.join(ROOT, "CHANGELOG.md")
BEGIN = "/* HELP_NEWS generated by docs/build-help-news.py -- do not edit by hand */"
END = "/* HELP_NEWS end */"
KEEP = 5

log = open(LOG, encoding="utf-8").read()
entries = re.split(r"^(?=## \d)", log, flags=re.M)[1:KEEP + 1]
news = "".join(entries).strip() + "\n"
app = open(APP, encoding="utf-8").read()
line = "const HELP_NEWS = " + json.dumps(news, ensure_ascii=False).replace("</", "<\\/") + ";"
out, n = re.subn(re.escape(BEGIN) + r"[\s\S]*?" + re.escape(END), lambda m: BEGIN + "\n" + line + "\n" + END, app)
if n != 1:
    raise SystemExit("could not find the HELP_NEWS markers in grouptodo.html")
if out != app:
    open(APP, "w", encoding="utf-8", newline="\n").write(out)
    print("wrote What's new into grouptodo.html")
