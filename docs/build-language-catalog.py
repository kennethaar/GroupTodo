"""Collect the words GroupToDo shows on screen into its English catalog.

    python docs/build-language-catalog.py

Reads every string literal in grouptodo.html's scripts that looks like text
for people (starts with a capital, has words, no code in it), plus sentences
glued together around a value ("Imported " + n + " file(s).") as templates
with {1}, {2} where the values go. Writes:

  - the LANG_CATALOG line in grouptodo.html, between the two markers, which the
    app uses to write 8/Languages/English.md into every area
  - languages/English.md, the same file, as the starting point for a
    translation shared on GitHub

Run it again after changing words in the app. A string missed here can still
be translated: add it to a language file by hand.
"""
import io
import json
import os
import re
from html import unescape
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "grouptodo.html")
OUT = os.path.join(ROOT, "languages", "English.md")
BEGIN = "/* LANG_CATALOG generated by docs/build-language-catalog.py -- do not edit by hand */"
END = "/* LANG_CATALOG end */"
BS = chr(92)

JUNK = re.compile(r"[<`\\]|=>|->|^\.(?! )|^#|\.replace\(|String\(|::|\bpx\b|var\(|rgba?\(|^https?:|\.(md|js|json|org|html|svg|ics)$"
                  r"|^[A-Z_0-9]+$|^\d+ ?-|^\d+$|=\"|^\"|\dpx|^\((max|min)-width|^\((prefers|pointer|hover)|^[A-Z][A-Z-]*(;[A-Z=-]+)*:$")


def literals(js):
    """(quote, raw text, start, end) for every string literal, skipping comments and regexes."""
    i, n = 0, len(js)
    while i < n:
        c = js[i]
        if js.startswith("//", i):
            j = js.find("\n", i); i = n if j < 0 else j; continue
        if js.startswith("/*", i):
            j = js.find("*/", i + 2); i = n if j < 0 else j + 2; continue
        if c in "\"'`":
            j = i + 1; buf = []
            while j < n and js[j] != c:
                if js[j] == BS: buf.append(js[j:j + 2]); j += 2; continue
                if c == "`" and js.startswith("${", j):
                    d = 1; j += 2
                    while j < n and d:
                        d += js[j] == "{"; d -= js[j] == "}"; j += 1
                    buf.append("\x00"); continue
                if js[j] == "\n" and c != "`": break
                buf.append(js[j]); j += 1
            yield c, "".join(buf), i, j + 1
            i = j + 1; continue
        if c == "/" and re.search(r"[(,=:\[!&|?{};]\s*$", js[max(0, i - 20):i]):
            j = i + 1; cls = False
            while j < n:
                if js[j] == BS: j += 2; continue
                if js[j] == "[": cls = True
                elif js[j] == "]": cls = False
                elif js[j] == "/" and not cls: break
                elif js[j] == "\n": break
                j += 1
            i = j + 1; continue
        i += 1


def decode(q, raw):
    if q == "`" or "\x00" in raw: return None
    try: return json.loads('"' + raw.replace('"', BS + '"').replace(BS + "'", "'") + '"')
    except Exception: return None


CSS_CLASSES = set()
CODE_BEFORE = re.compile(
    r"(?:(?:class|className|style|type|role|id|key|kind|mode|method|rel|target|inputmode|autocomplete|"
    r"spellcheck|contenteditable|href|src|for|value|lang|dir|accept|cache|credentials|tag|state|op|event|"
    r"display|level|align|justify|position|cursor|color|background|font|width|height)\s*:\s*$)"
    r"|(?:(?:className|\.type|\.key|\.code|\.kind|\.mode|\.id|\.state|\.name|\.tagName|\.cssText|\.display)\s*=\s*$)"
    r"|(?:(?:===|!==|==|!=)\s*$)|(?:case\s+$)|(?:\w\[\s*$)"
    r"|(?:(?:querySelector(?:All)?|closest|matches|\$\$?|getElementById|classList\.\w+|addEventListener|"
    r"removeEventListener|setAttribute|getAttribute|removeAttribute|hasAttribute|toggleAttribute|createElement|"
    r"createElementNS|el|startsWith|endsWith|includes|indexOf|lastIndexOf|split|join|replace|replaceAll|test|"
    r"getItem|setItem|removeItem|get|set|has|delete|getSetting|setSetting|fetch|RegExp|toggle|"
    r"getPropertyValue|setProperty|postMessage|dispatchEvent|Event|CustomEvent|execCommand)\s*\(\s*$)")


def wordy(t):
    return bool(re.search(r"[A-Za-zÀ-ɏ]{2}", t))


def ui_text(t, braces_ok=False):
    if len(t) < 2 or len(t) > 1500 or not wordy(t): return False
    if not re.search(r"\s", t) and not re.match(r"[A-ZÀ-Þ]", t): return False   # one lowercase word: code
    if JUNK.search(t): return False
    if not braces_ok and re.search(r"[{}]", t): return False
    if re.fullmatch(r"[A-Z][a-z]+[A-Z]\w*", t): return False      # camelCase ids
    if re.match(r"[a-z0-9_.-]+/", t): return False                 # paths
    if CSS_CLASSES and all(w in CSS_CLASSES for w in t.split()): return False   # class names
    return True


def plain_expr(e):
    """A value between two strings: no strings, no ternary, no top-level comma."""
    if not e or len(e) > 90 or "\n" in e or re.search(r"[\"'`?;]", e): return False
    depth = 0
    for ch in e:
        depth += ch in "([{"; depth -= ch in ")]}"
        if depth < 0 or (ch == "," and depth == 0): return False
    return depth == 0


PLUS = re.compile(r"\s*\+\s*", re.S)                       # "a" + "b"
GLUE = re.compile(r"\s*\+\s*(.+?)\s*\+\s*", re.S)           # "a" + value + "b"
TAIL = re.compile(r"\s*\+\s*([^\"'`\n]+?)\s*(?=[),;\]}])")  # "a" + value)
HEAD = re.compile(r"(?:^|[(,=:?\[]|return)\s*([\w$.]+(?:\([^()\"'`\n]*\))?)\s*\+\s*$")  # value + "a"


def catalog(html):
    html = re.sub(re.escape(BEGIN) + r"[\s\S]*?" + re.escape(END), "", html)
    for m in re.finditer(r"<style[^>]*>([\s\S]*?)</style>", html):
        CSS_CLASSES.update(re.findall(r"\.([a-zA-Z][\w-]*)", m.group(1)))
    strings, templates = set(), set()
    for m in re.finditer(r"<script>([\s\S]*?)</script>", html):
        js = m.group(1)
        toks = list(literals(js))
        k = 0
        while k < len(toks):
            q, raw, s, e = toks[k]
            t = decode(q, raw)
            if t is None: k += 1; continue
            # One sentence, as it reaches the screen: literals glued with +, and
            # a {n} wherever a value is glued in between.
            before = js[max(0, s - 120):s]
            if CODE_BEFORE.search(before[-80:]): k += 1; continue
            parts = [None] if HEAD.search(before) else []
            if not parts and re.search(r"\+\s*$", before): k += 1; continue   # inside a longer expression
            parts.append(t)
            last = k
            while last + 1 < len(toks):
                q2, raw2, s2, e2 = toks[last + 1]
                t2 = decode(q2, raw2)
                if t2 is None: break
                gap = js[toks[last][3]:s2]
                if PLUS.fullmatch(gap):
                    parts[-1] = (parts[-1] or "") + t2 if parts[-1] is not None else t2
                elif (g := GLUE.fullmatch(gap)) and plain_expr(g.group(1)):
                    parts += [None, t2]
                else: break
                last += 1
            tail = TAIL.match(js, toks[last][3])
            if tail and plain_expr(tail.group(1)): parts.append(None)
            k = last + 1
            out, n = "", 0
            for p in parts:
                if p is None: n += 1; out += "{" + str(n) + "}"
                else: out += p
            out = re.sub(r"\s+", " ", out).strip()
            if not n:
                if ui_text(out): strings.add(out)
                continue
            words = re.sub(r"\{\d+\}", "", out)
            if ui_text(out, braces_ok=True) or (out.startswith("{1}") and ui_text("X" + out[3:], braces_ok=True)):
                if len(words.split()) >= 2 and not re.search(r"[{}]", words) and re.search(r"[A-Za-z]{3}", words):
                    templates.add(out)
    # Text written straight into the page: the help panel, the top bar.
    body = re.sub(r"<script[\s\S]*?</script>|<style[\s\S]*?</style>|<!--[\s\S]*?-->", "", html)
    for m in re.finditer(r">([^<>]+)<", body):
        t = re.sub(r"\s+", " ", unescape(m.group(1))).strip()
        if ui_text(t): strings.add(t)
    for m in re.finditer(r"(?:title|placeholder|aria-label|alt)=\"([^\"]+)\"", body):
        t = re.sub(r"\s+", " ", unescape(m.group(1))).strip()
        if ui_text(t): strings.add(t)
    return sorted(strings), sorted(templates - strings)


def english_file(strings, templates):
    lines = [
        "language:: English",
        "code:: en",
        "",
        "# GroupToDo language file. One line per piece of text on screen.",
        "# A translation goes after =>, for example:   Today => I dag",
        "# {1}, {2} stand for a number or name the app fills in; keep them in the translation.",
        "# A line with nothing after => stays in English. Lines starting with # are notes.",
        "",
    ]
    lines += [s + " =>" for s in strings]
    lines += ["", "# Sentences with a value in them"]
    lines += [s + " =>" for s in templates]
    return "\n".join(lines) + "\n"


def main():
    html = open(APP, encoding="utf-8", newline="").read()
    strings, templates = catalog(html)
    line = BEGIN + "\nconst LANG_CATALOG = " + json.dumps({"s": strings, "t": templates},
                                                        ensure_ascii=False, separators=(",", ":")) + ";\n" + END
    if BEGIN not in html:
        sys.exit("Markers not found in grouptodo.html -- add them where LANG_CATALOG belongs.")
    html = re.sub(re.escape(BEGIN) + r"[\s\S]*?" + re.escape(END), lambda _: line, html)
    open(APP, "w", encoding="utf-8", newline="").write(html)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(english_file(strings, templates))
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    print(len(strings), "strings,", len(templates), "templates")


if __name__ == "__main__":
    main()
