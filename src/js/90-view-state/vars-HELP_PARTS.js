/* ---------- the help, as data ----------
   Every topic is one screen: what it is, the steps, the keys, and a fold for
   the rest. The full help, its search and "This page" beside the view are
   three ways of showing the same table, so they can never disagree.

   A topic with a view (and sub) is that screen's own: ? there opens it. Its
   legend is what "Show me" points at: a selector, and what the thing is. A
   selector starting with ? may be missing, since it only shows when there is
   something for it (a late task, a twin). steps can be [text, selector] for a
   step with a "Show me" of its own. words are what people call it instead.
   The screenshot docs/help/<id>.jpg is made by tests/screenshots.mjs. */
