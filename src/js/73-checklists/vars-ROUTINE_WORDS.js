/* Three things live in this folder and they are not the same thing:

     a project   finishes  -- "Move house", ticked off once and gone
     a routine   returns   -- "Weekly accounts", never finished, only due again
     a template  breeds    -- "Onboard customer", one new project per run

   Filing a routine as a project is the commonest way a GTD list goes bad: it
   sits in Active looking undone forever, and everything around it starts to
   feel undone too. So the words are asked for at the moment of naming, where
   changing your mind is free. */
const ROUTINE_WORDS = /\b(daily|weekly|fortnightly|monthly|quarterly|yearly|annual(?:ly)?|routine|recurring|upkeep|maintenance|housekeeping|habit|stand-?up|check-?ins?|every (?:day|week|month|morning|evening|monday|tuesday|wednesday|thursday|friday|saturday|sunday)|each (?:day|week|month|morning))\b/i;
